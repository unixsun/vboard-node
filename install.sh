#!/usr/bin/env bash
set -euo pipefail

APP_NAME="vboard-node"
DEFAULT_ACTION="install"
DEFAULT_MODE="machine"
DEFAULT_KERNEL="sing-box"
DEFAULT_KERNEL_MODE="embedded"
DEFAULT_INTERVAL="30"
DEFAULT_INSTALL_DIR="/usr/local/bin"
DEFAULT_CONFIG_DIR="/etc/vboard-node"
DEFAULT_RUNTIME_DIR="/var/lib/vboard-node"
DEFAULT_USER="root"
DEFAULT_BINARY_URL=""
DEFAULT_RELEASE_BASE="https://github.com/unixsun/vboard-node/releases"
DEFAULT_RELEASE_VERSION="latest"
DEFAULT_SING_BOX_VERSION=""
DEFAULT_STATS_API="127.0.0.1:10085"

ACTION="${DEFAULT_ACTION}"
MODE="${DEFAULT_MODE}"
PANEL_URL=""
TOKEN=""
MACHINE_ID=""
KERNEL="${DEFAULT_KERNEL}"
KERNEL_MODE="${VBOARD_NODE_KERNEL_MODE:-${DEFAULT_KERNEL_MODE}}"
INTERVAL="${DEFAULT_INTERVAL}"
INSTALL_DIR="${DEFAULT_INSTALL_DIR}"
CONFIG_DIR="${DEFAULT_CONFIG_DIR}"
RUNTIME_DIR="${DEFAULT_RUNTIME_DIR}"
RUN_USER="${DEFAULT_USER}"
BINARY_URL="${VBOARD_NODE_BINARY_URL:-${DEFAULT_BINARY_URL}}"
RELEASE_BASE="${VBOARD_NODE_RELEASE_BASE:-${DEFAULT_RELEASE_BASE}}"
RELEASE_VERSION="${VBOARD_NODE_RELEASE_VERSION:-${DEFAULT_RELEASE_VERSION}}"
BINARY_SHA256="${VBOARD_NODE_BINARY_SHA256:-}"
CHECKSUM_URL="${VBOARD_NODE_CHECKSUM_URL:-}"
SKIP_CHECKSUM="${VBOARD_NODE_SKIP_CHECKSUM:-false}"
ENABLE_KERNEL="false"
ENABLE_UPGRADE="${VBOARD_NODE_ENABLE_UPGRADE:-false}"
SING_BOX_BIN="sing-box"
SING_BOX_BIN_SET="false"
STATS_API="${VBOARD_NODE_STATS_API:-${DEFAULT_STATS_API}}"
INSTALL_SING_BOX="${VBOARD_NODE_INSTALL_SING_BOX:-auto}"
SING_BOX_VERSION="${VBOARD_NODE_SING_BOX_VERSION:-${DEFAULT_SING_BOX_VERSION}}"
SELF_TEST="${VBOARD_NODE_SELF_TEST:-true}"
CERTIFICATE_PATH="${VBOARD_NODE_CERTIFICATE_PATH:-}"
PRIVATE_KEY_PATH="${VBOARD_NODE_PRIVATE_KEY_PATH:-}"
SERVICE_FILE="/etc/systemd/system/${APP_NAME}.service"
UPGRADE_SERVICE_FILE="/etc/systemd/system/${APP_NAME}-upgrade.service"
ENV_FILE="${CONFIG_DIR}/vboard-node.env"
BACKUP_DIR="${CONFIG_DIR}/backups"
BACKUP_PATH=""
TMP_DIR=""
ROLLBACK_READY="false"
SERVICE_EXISTED="false"
STAGED_BINARY=""

usage() {
  cat <<'USAGE'
Install and manage vboard-node.

Usage:
  install.sh [install] --mode machine --panel <url> --token <token> --machine-id <sid> [options]
  install.sh upgrade [--version <version>] [download options]
  install.sh status
  install.sh uninstall

Required:
  --panel <url>          VBoard API URL, for example https://panel.example.com or http://10.0.0.1:8080
  --token <token>        Server token generated by the panel
