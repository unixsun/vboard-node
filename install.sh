  --kernel-mode <mode>   Kernel runtime: embedded or external (default: embedded)
  --interval <seconds>   Sync interval in seconds (default: 30)
  --binary-url <url>     vboard-node binary download URL
  --release-base <url>   GitHub Releases base URL, ending with /releases
  --version <version>    Release tag or latest (default: latest)
