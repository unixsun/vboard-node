EOF

  chmod 0644 "$SERVICE_FILE"
  write_upgrade_service
  systemctl daemon-reload
  systemctl enable "$APP_NAME"
  systemctl restart --no-block "$APP_NAME"
  local attempt state
  for attempt in $(seq 1 30); do
    sleep 1
    state="$(systemctl is-active "$APP_NAME" 2>/dev/null || true)"
    case "$state" in
      active)
        sleep 2
        if [ "$(systemctl is-active "$APP_NAME" 2>/dev/null || true)" = "active" ]; then
          log "service is running: ${APP_NAME}"
          break
        fi
        ;;
      failed)
        systemctl status "$APP_NAME" --no-pager -l >&2 || true
        fatal "systemd service failed to start: ${APP_NAME}"
        ;;
    esac
  done
  [ "${state:-}" = "active" ] || fatal "timed out waiting for systemd service: ${APP_NAME}"
  log "installed systemd service: $SERVICE_FILE"
}

write_upgrade_service() {
  if [ "$ENABLE_UPGRADE" != "true" ]; then
    rm -f "$UPGRADE_SERVICE_FILE"
    return
  fi
  local upgrade_backup_dir
  upgrade_backup_dir="$(dirname "$RUNTIME_DIR")/vboard-node-backups"
  mkdir -p "$upgrade_backup_dir"
  chmod 0700 "$upgrade_backup_dir"
  cat >"$UPGRADE_SERVICE_FILE" <<EOF
[Unit]
Description=VBoard Node Controlled Upgrade
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
User=root
ExecStart=${INSTALL_DIR}/${APP_NAME} --apply-upgrade ${RUNTIME_DIR}/upgrade-request.json
NoNewPrivileges=true
PrivateTmp=true
ProtectHome=true
ProtectSystem=full
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
LockPersonality=true
ReadWritePaths=${INSTALL_DIR} ${RUNTIME_DIR} ${upgrade_backup_dir}
EOF
  chmod 0644 "$UPGRADE_SERVICE_FILE"
}

show_status() {
  refresh_paths
  printf 'vboard-node status\n'
  printf '  binary:  %s\n' "${INSTALL_DIR}/${APP_NAME}"
  printf '  config:  %s\n' "$ENV_FILE"
  printf '  service: %s\n' "$SERVICE_FILE"
  if [ -x "${INSTALL_DIR}/${APP_NAME}" ]; then
    "${INSTALL_DIR}/${APP_NAME}" --help >/dev/null 2>&1 &&
      printf '  binary check: ok\n' ||
      printf '  binary check: failed\n'
  else
    printf '  binary check: missing\n'
  fi
  if command -v systemctl >/dev/null 2>&1 && [ -f "$SERVICE_FILE" ]; then
    systemctl status "$APP_NAME" --no-pager || true
  fi
}

uninstall_node() {
  need_root
  refresh_paths
  systemctl disable --now "$APP_NAME" >/dev/null 2>&1 || true
  rm -f "$SERVICE_FILE" "$UPGRADE_SERVICE_FILE" "${INSTALL_DIR}/${APP_NAME}"
  systemctl daemon-reload >/dev/null 2>&1 || true
  log "service and binary removed; configuration retained at $CONFIG_DIR"
}

main() {
  parse_args "$@"
  refresh_paths

  case "$ACTION" in
    status)
      show_status
      return
      ;;
    uninstall)
      uninstall_node
      return
      ;;
    upgrade)
      load_existing_config
      if [ -z "$BINARY_URL" ] && [ -z "$RELEASE_BASE" ]; then
        fatal "upgrade requires --binary-url or --release-base"
      fi
      ;;
    install) ;;
    *) fatal "unsupported action: $ACTION" ;;
  esac

  validate_args
  need_root
  command -v curl >/dev/null 2>&1 || fatal "curl is required"
  command -v systemctl >/dev/null 2>&1 || fatal "systemd is required"

  stage_binary
  backup_existing_state
  install_staged_binary "$STAGED_BINARY"
  ensure_sing_box
  write_env_file
  self_test
  write_systemd_service
  ROLLBACK_READY="false"
  log "${ACTION} complete"
  log "status: systemctl status ${APP_NAME} --no-pager"
  log "logs: journalctl -u ${APP_NAME} -f"
}

main "$@"
